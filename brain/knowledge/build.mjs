// Builds knowledge.md: the only facts the agent may use about Santiago.
// Sources (allowlist): the portfolio's content.js and the public résumé text in sources/.
// Run after any portfolio copy change:  npm run knowledge
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const portfolioDir = process.env.PORTFOLIO_DIR || path.resolve(here, "../../../portfolio");

function loadContent() {
  const src = fs.readFileSync(path.join(portfolioDir, "content.js"), "utf8");
  const sandbox = { window: {} };
  vm.runInNewContext(src, sandbox);
  return sandbox.window.CONTENT;
}

// Drafts on the site start with "TODO"; they are not facts.
const real = (s) => typeof s === "string" && s.trim() && !s.trim().startsWith("TODO");

export function renderPortfolio(c) {
  const out = [];
  out.push(`## Portfolio site (santiagolabarca.vercel.app)`);
  if (real(c.hero.eyebrow)) out.push(`Positioning: ${c.hero.eyebrow}`);
  if (real(c.hero.tagline)) out.push(`Tagline: ${c.hero.tagline}`);
  if (real(c.hero.sub)) out.push(c.hero.sub);

  out.push(`\n### Experience by company (newest first)`);
  const themes = Object.fromEntries(c.themes.map((t) => [t.id, t.label]));
  for (const co of c.companies) {
    const roles = co.roles.map((r) => `${r.title} (${r.period})`).join("; ");
    out.push(`\n#### ${co.name} — ${co.place}`);
    if (real(co.context)) out.push(co.context);
    out.push(`Roles: ${roles}`);
    for (const r of c.results.filter((r) => r.company === co.id)) {
      const bullets = (r.bullets || []).filter(real).map((b) => `  - ${b}`).join("\n");
      out.push(`- ${r.headline} [${themes[r.theme] || r.theme}; ${r.role}]\n${bullets}`);
    }
  }

  out.push(`\n### Personal projects`);
  for (const p of c.projects) {
    out.push(`\n#### ${p.name} (${p.kicker})`);
    if (real(p.brief)) out.push(p.brief);
    for (const b of p.boxes || []) out.push(`- ${b.title}: ${b.text} ${b.detail || ""}`.trim());
    if (p.approach) {
      out.push(`${p.approach.title}:`);
      for (const s of p.approach.steps) out.push(`- ${s.label}: ${s.text}`);
    }
    if (p.stack?.length) out.push(`Stack: ${p.stack.join(", ")}`);
    const links = (p.links || []).map((l) => (l.href ? `${l.label}: ${l.href}` : l.label));
    if (links.length) out.push(`Links: ${links.join(" · ")}`);
  }

  out.push(`\n### About`);
  for (const p of c.about.bio.filter(real)) out.push(p);
  out.push(`Interests: ${c.about.interests.join("; ")}`);
  out.push(`Education: ${c.about.education.map((e) => `${e.school}, ${e.degree} (${e.period})`).join("; ")}`);
  out.push(`Contact: ${c.about.links.map((l) => `${l.label} ${l.href.replace("mailto:", "")}`).join(" · ")}`);
  return out.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const resume = fs.readFileSync(path.join(here, "sources/resume.txt"), "utf8").trim();
  const md = [
    `# Knowledge pack — generated by brain/knowledge/build.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.`,
    `\n## Résumé (authoritative for every number and date)\n\n${resume}`,
    `\n${renderPortfolio(loadContent())}`,
  ].join("\n");
  fs.writeFileSync(path.join(here, "knowledge.md"), md + "\n");
  console.log(`knowledge.md: ${md.length} chars (~${Math.round(md.length / 4)} tokens)`);
}
